#[derive(Debug, Clone, Default)]
pub struct AvifColorInfo {
    pub primaries: Option<u16>,
    pub transfer: Option<u16>,
    pub matrix: Option<u16>,
    pub full_range: Option<bool>,
    pub icc_profile: Option<Vec<u8>>,
}

impl AvifColorInfo {
    pub fn should_correct_matrix(&self) -> bool {
        // Matrix 6 is ST 170M (standard BT.601 NTSC).
        // image crate 0.25 maps ST170M to Smpte240 with inverted kr/kb coefficients,
        // causing a +30.2% red chroma factor error and green channel distortion.
        self.matrix == Some(6)
    }
}

/// Parses an ISOBMFF/AVIF byte buffer to extract color metadata from the `colr` box.
pub fn parse_avif_color_info(data: &[u8]) -> Option<AvifColorInfo> {
    if data.len() < 12 || &data[4..8] != b"ftyp" {
        return None;
    }

    let mut info = AvifColorInfo::default();
    let mut found = false;

    scan_boxes(data, 0, data.len(), &mut info, &mut found);

    if found {
        Some(info)
    } else {
        None
    }
}

fn scan_boxes(
    data: &[u8],
    start: usize,
    end: usize,
    info: &mut AvifColorInfo,
    found: &mut bool,
) {
    let mut pos = start;
    while pos + 8 <= end {
        let size_u32 = u32::from_be_bytes([data[pos], data[pos + 1], data[pos + 2], data[pos + 3]]) as usize;
        let fourcc = &data[pos + 4..pos + 8];
        let mut hdr = 8;
        let size = if size_u32 == 1 {
            if pos + 16 > end {
                break;
            }
            hdr = 16;
            u64::from_be_bytes([
                data[pos + 8], data[pos + 9], data[pos + 10], data[pos + 11],
                data[pos + 12], data[pos + 13], data[pos + 14], data[pos + 15],
            ]) as usize
        } else if size_u32 == 0 {
            end - pos
        } else {
            size_u32
        };

        if size < hdr || pos + size > end {
            break;
        }

        let box_end = pos + size;

        if fourcc == b"colr" {
            if box_end - pos >= hdr + 4 {
                let color_type = &data[pos + hdr..pos + hdr + 4];
                if color_type == b"nclx" && box_end - pos >= hdr + 11 {
                    let p = u16::from_be_bytes([data[pos + hdr + 4], data[pos + hdr + 5]]);
                    let t = u16::from_be_bytes([data[pos + hdr + 6], data[pos + hdr + 7]]);
                    let m = u16::from_be_bytes([data[pos + hdr + 8], data[pos + hdr + 9]]);
                    let f = (data[pos + hdr + 10] & 0x80) != 0;

                    info.primaries = Some(p);
                    info.transfer = Some(t);
                    info.matrix = Some(m);
                    info.full_range = Some(f);

                    // If wide-gamut primaries are used, attach matching ICC profile
                    if p == 12 && info.icc_profile.is_none() {
                        // Display P3 (SMPTE EG 432-1)
                        info.icc_profile = Some(DISPLAY_P3_ICC.to_vec());
                    } else if p == 9 && info.icc_profile.is_none() {
                        // ITU-R BT.2020
                        info.icc_profile = Some(REC2020_ICC.to_vec());
                    }

                    *found = true;
                    return;
                } else if (color_type == b"rICC" || color_type == b"prof") && box_end - pos > hdr + 4 {
                    let icc_data = &data[pos + hdr + 4..box_end];
                    info.icc_profile = Some(icc_data.to_vec());
                    *found = true;
                    return;
                }
            }
        } else if fourcc == b"meta" || fourcc == b"iprp" || fourcc == b"ipco" {
            let mut sub_start = pos + hdr;
            if fourcc == b"meta" && sub_start + 4 <= box_end {
                sub_start += 4; // Skip FullBox version (1) + flags (3)
            }
            scan_boxes(data, sub_start, box_end, info, found);
            if *found {
                return;
            }
        }

        pos = box_end;
    }
}

/// Applies linear matrix correction to fix image crate 0.25's SMPTE 170M bug.
///
/// In image crate 0.25 (codecs/avif/decoder.rs & yuv.rs), MatrixCoefficients::ST170M
/// is mapped to Smpte240 with inverted kr/kb coefficients (kr=0.087, kb=0.212).
///
/// The correction matrix T = M_bt601 * M_buggy^-1:
///   R' =  0.788000 * R + 0.162773 * G + 0.049227 * B
///   G' = -0.251071 * R + 1.128227 * G + 0.122844 * B
///   B' = -0.010820 * R - 0.087180 * G + 1.098000 * B
///
/// Each row sums exactly to 1.0, preserving neutral grays (R=G=B) with zero shift.
#[inline(always)]
fn correct_rgb(r: u8, g: u8, b: u8) -> (u8, u8, u8) {
    let rf = r as f32;
    let gf = g as f32;
    let bf = b as f32;

    let r_out = 0.788000 * rf + 0.162773 * gf + 0.049227 * bf;
    let g_out = -0.251071 * rf + 1.128227 * gf + 0.122844 * bf;
    let b_out = -0.010820 * rf - 0.087180 * gf + 1.098000 * bf;

    (
        r_out.clamp(0.0, 255.0).round() as u8,
        g_out.clamp(0.0, 255.0).round() as u8,
        b_out.clamp(0.0, 255.0).round() as u8,
    )
}

#[inline(always)]
fn correct_rgb16(r: u16, g: u16, b: u16) -> (u16, u16, u16) {
    let rf = r as f32;
    let gf = g as f32;
    let bf = b as f32;

    let r_out = 0.788000 * rf + 0.162773 * gf + 0.049227 * bf;
    let g_out = -0.251071 * rf + 1.128227 * gf + 0.122844 * bf;
    let b_out = -0.010820 * rf - 0.087180 * gf + 1.098000 * bf;

    (
        r_out.clamp(0.0, 65535.0).round() as u16,
        g_out.clamp(0.0, 65535.0).round() as u16,
        b_out.clamp(0.0, 65535.0).round() as u16,
    )
}

pub fn correct_avif_matrix(image: &mut DynamicImage) {
    match image {
        DynamicImage::ImageRgb8(img) => {
            for pixel in img.pixels_mut() {
                let (r, g, b) = correct_rgb(pixel[0], pixel[1], pixel[2]);
                pixel[0] = r;
                pixel[1] = g;
                pixel[2] = b;
            }
        }
        DynamicImage::ImageRgba8(img) => {
            for pixel in img.pixels_mut() {
                let (r, g, b) = correct_rgb(pixel[0], pixel[1], pixel[2]);
                pixel[0] = r;
                pixel[1] = g;
                pixel[2] = b;
            }
        }
        DynamicImage::ImageRgb16(img) => {
            for pixel in img.pixels_mut() {
                let (r, g, b) = correct_rgb16(pixel[0], pixel[1], pixel[2]);
                pixel[0] = r;
                pixel[1] = g;
                pixel[2] = b;
            }
        }
        DynamicImage::ImageRgba16(img) => {
            for pixel in img.pixels_mut() {
                let (r, g, b) = correct_rgb16(pixel[0], pixel[1], pixel[2]);
                pixel[0] = r;
                pixel[1] = g;
                pixel[2] = b;
            }
        }
        _ => {}
    }
}